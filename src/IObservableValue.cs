using System;

namespace ReactiveCollections
{
    /// <summary>
    /// Контракт реактивного одиночного значения: чтение + событие изменений.
    /// </summary>
    /// <typeparam name="T">Тип значения.</typeparam>
    /// <remarks>
    /// Аналог <see cref="IObservableList{T}"/> для одного значения. Используется
    /// для агрегатов и для пользовательских значений, которые нужно наблюдать.
    /// Потокобезопасность не гарантируется.
    /// </remarks>
    public interface IObservableValue<T> : IDisposable
    {
        /// <summary>
        /// Текущее значение.
        /// </summary>
        /// <remarks>
        /// После <see cref="IDisposable.Dispose"/> чтение разрешено и возвращает
        /// последнее установленное значение.
        /// </remarks>
        T Value { get; }

        /// <summary>
        /// Возникает при установке или обновлении значения.
        /// </summary>
        /// <remarks>
        /// Событие райзится после применения изменения, поэтому в обработчике
        /// <see cref="Value"/> содержит актуальное значение. Если один подписчик
        /// выбрасывает исключение, остальные всё равно получают событие, а
        /// исключения пробрасываются вызывающему после обхода всех подписчиков.
        /// </remarks>
        event Action<ValueChange<T>>? Changed;
    }
}