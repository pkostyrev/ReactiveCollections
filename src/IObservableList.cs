using System;
using System.Collections.Generic;

namespace ReactiveCollections
{
    /// <summary>
    /// Единый контракт для всех реактивных коллекций: чтение, событие изменений
    /// и освобождение подписок.
    /// </summary>
    /// <typeparam name="T">Тип элемента коллекции.</typeparam>
    /// <remarks>
    /// <para>
    /// Реализуется двумя категориями типов:
    /// <list type="bullet">
    /// <item>Источники — например, <see cref="ObservableList{T}"/>.
    ///     Создаются пользователем вручную и мутируются через публичный API.</item>
    /// <item>Проекции — например, <see cref="FilterNode{T}"/>,
    ///     <see cref="SelectNode{TSource, TResult}"/>. Создаются через extension-методы
    ///     (<see cref="ObservableExtensions"/>) и обновляются автоматически.</item>
    /// </list>
    /// </para>
    /// <para>
    /// Контракт не гарантирует потокобезопасность. Все изменения должны происходить
    /// в одном потоке — см. README, раздел 4.7.
    /// </para>
    /// </remarks>
    public interface IObservableList<T> : IReadOnlyList<T>, IDisposable
    {
        /// <summary>
        /// Возникает при каждом изменении коллекции.
        /// </summary>
        /// <remarks>
        /// <para>
        /// Событие райзится <b>после</b> применения изменения к состоянию коллекции.
        /// Подписчик, читающий коллекцию в обработчике, видит уже новое состояние.
        /// </para>
        /// <para>
        /// Порядок событий соответствует порядку операций над источником.
        /// Если один подписчик выбрасывает исключение, остальные всё равно
        /// получают событие (см. README, раздел 4.8). Исключения пробрасываются
        /// вызывающему после обхода всех подписчиков.
        /// </para>
        /// <para>
        /// Исключения в подписчиках не отменяют уже применённое изменение:
        /// состояние коллекции и события находятся в слабой синхронизации.
        /// </para>
        /// </remarks>
        event Action<Change<T>>? Changed;
    }
}